"""Compute risk levels from data/risk_register.csv (NIST SP 800-30 Rev.1 G-5 and I-2).

    python risk.py           # writes out/register.md and out/matrix.md
    python risk.py --check   # runs the self-check

Only derived values are computed here. Human ratings and decisions stay in the CSV
and report.md. The script flags what policy requires; it never accepts a risk.
"""
import csv
import re
import sys
from pathlib import Path

ROOT = Path(__file__).parent
LEVELS = ['Very Low', 'Low', 'Moderate', 'High', 'Very High']
VL, L, M, H, VH = LEVELS

# Verbatim from SP 800-30 Rev.1 (pages G-2 and I-1). Row = first factor, columns = second factor VL..VH.
G5 = {VH: [L, M, H, VH, VH], H: [L, M, M, H, VH], M: [L, L, M, M, H], L: [VL, L, L, M, M], VL: [VL, VL, L, L, L]}
I2 = {VH: [VL, L, M, H, VH], H: [VL, L, M, H, VH], M: [VL, L, M, M, H], L: [VL, L, L, L, M], VL: [VL, VL, VL, L, L]}


def level(value, field, rid):
    if value not in LEVELS:
        raise ValueError(f'{rid}: {field}={value!r} is not one of {LEVELS}')
    return value


def overall_likelihood(initiation, adverse):
    return G5[initiation][LEVELS.index(adverse)]


def risk_level(likelihood, impact):
    return I2[likelihood][LEVELS.index(impact)]


def policy_flags(risk, impact):
    """report.md 1.6: what the decision policy requires. Never grants acceptance."""
    flags = {VL: 'owner may accept', L: 'owner may accept', M: 'treat or delegated acceptance',
             H: 'treat or senior exception', VH: 'treat or senior exception'}[risk]
    return flags + ('; ESCALATE' if impact == VH else '')


def assess(row, prefix=''):
    """Return (overall likelihood, risk), or None when a rating is missing or 'unknown'."""
    fields = [prefix + 'initiation_likelihood', prefix + 'adverse_impact_likelihood', prefix + 'impact']
    values = [row[f] for f in fields]
    if 'unknown' in values or '' in values:
        return None
    a, b, imp = (level(v, f, row['risk_id']) for v, f in zip(values, fields))
    ol = overall_likelihood(a, b)
    return ol, risk_level(ol, imp)


def evaluate(rows):
    out, warnings = [], []
    for r in rows:
        cur = assess(r)
        if cur is None:
            warnings.append(f"{r['risk_id']}: current rating missing or unknown, row skipped")
            continue
        res = assess(r, 'residual_') if r['residual_status'] != 'not_assessed' else None
        out.append({**r, 'overall': cur[0], 'risk': cur[1], 'flags': policy_flags(cur[1], r['impact']),
                    'res_overall': res[0] if res else '', 'res_risk': res[1] if res else '',
                    'res_impact': r['residual_impact'] if res else ''})
    # report.md 3.5: risk, impact, overall likelihood (all descending), then lower confidence first
    conf = {'Low': 0, 'Medium': 1, 'High': 2}
    out.sort(key=lambda x: (-LEVELS.index(x['risk']), -LEVELS.index(x['impact']),
                            -LEVELS.index(x['overall']), conf.get(x['confidence'], 0), x['risk_id']))
    return out, warnings


def matrix(rows, lk, ik, rk, title):
    lines = [f'### {title}', '', '| Likelihood \\ Impact | ' + ' | '.join(LEVELS) + ' |', '|---' * 6 + '|']
    for lv in reversed(LEVELS):
        cells = [', '.join(r['risk_id'] for r in rows if r[lk] == lv and r[ik] == iv) for iv in LEVELS]
        lines.append(f'| **{lv}** | ' + ' | '.join(cells) + ' |')
    counts = ', '.join(f'{lv} {sum(r[rk] == lv for r in rows)}' for lv in LEVELS)
    return lines + ['', f'Risk levels: {counts}', '']


def render(rows, warnings):
    note = '> Generated by `python risk.py` from data/risk_register.csv. Do not edit by hand.\n'
    reg = ['# Risk register (generated)', '', note,
           '| # | Risk | Assets | Overall likelihood | Impact | Risk | Policy flags | Option | Residual risk | Residual status |',
           '|---' * 10 + '|']
    for i, r in enumerate(rows, 1):
        reg.append(f"| {i} | {r['risk_id']} | {r['asset_id'].replace(';', ', ')} | {r['overall']} | {r['impact']} | "
                   f"**{r['risk']}** | {r['flags']} | {r['treatment_option'] or '-'} | {r['res_risk'] or '-'} | "
                   f"{r['residual_status']} |")
    if warnings:
        reg += ['', '## Warnings', ''] + [f'- {w}' for w in warnings]
    mat = (['# Risk matrix (generated)', '', note]
           + matrix(rows, 'overall', 'impact', 'risk', 'Current risk')
           + matrix([r for r in rows if r['res_risk']], 'res_overall', 'res_impact', 'res_risk',
                    'Residual risk (projected unless verified)'))
    return '\n'.join(reg) + '\n', '\n'.join(mat)


def load(path):
    with open(path, encoding='utf-8', newline='') as f:
        return list(csv.DictReader(f))


def check():
    # 1. Tables in this file match the verbatim tables in PLAN.md (catches transcription errors).
    plan = (ROOT / 'PLAN.md').read_text(encoding='utf-8')
    abbr = {'VL': VL, 'L': L, 'M': M, 'H': H, 'VH': VH}
    for name, table in (('G-5', G5), ('I-2', I2)):
        block = plan.split(f'**{name},')[1].split('\n\n')[1]
        rows = re.findall(r'^\s*\| \*\*(\w+)\*\* \|(.*)\|$', block, re.M)
        assert len(rows) == 5, name
        for key, cells in rows:
            assert table[abbr[key]] == [abbr[c.strip()] for c in cells.split('|')], (name, key)
    # 2. Worked examples in report.md 3.1 / 3.2.
    assert risk_level(overall_likelihood(M, H), VH) == H                       # R-01
    assert risk_level(overall_likelihood(H, L), L) == L                        # R-10
    # 3. Escalation on Very High impact regardless of risk level.
    assert policy_flags(M, VH).endswith('ESCALATE') and 'ESCALATE' not in policy_flags(H, H)
    # 4. Invalid labels fail loudly; 'unknown' is skipped with a warning, never treated as zero.
    base = {'risk_id': 'X', 'initiation_likelihood': 'Moderate', 'adverse_impact_likelihood': 'High',
            'impact': 'Very High', 'residual_status': 'not_assessed', 'confidence': 'Low'}
    try:
        assess({**base, 'impact': 'Medium'})
        raise AssertionError('invalid label accepted')
    except ValueError:
        pass
    out, warns = evaluate([{**base, 'impact': 'unknown'}])
    assert out == [] and len(warns) == 1
    # 5. The real register evaluates without warnings.
    out, warns = evaluate(load(ROOT / 'data' / 'risk_register.csv'))
    assert len(out) == 13 and not warns, warns
    print('self-check passed')


def main():
    if '--check' in sys.argv:
        return check()
    rows, warnings = evaluate(load(ROOT / 'data' / 'risk_register.csv'))
    reg, mat = render(rows, warnings)
    (ROOT / 'out').mkdir(exist_ok=True)
    (ROOT / 'out' / 'register.md').write_text(reg, encoding='utf-8')
    (ROOT / 'out' / 'matrix.md').write_text(mat, encoding='utf-8')
    for w in warnings:
        print('WARNING:', w, file=sys.stderr)
    print(f'wrote out/register.md and out/matrix.md ({len(rows)} risks)')


if __name__ == '__main__':
    main()
